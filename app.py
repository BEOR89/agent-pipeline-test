def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

def multiply(a, b):
    """Returns product of two numbers."""
    return a * b

def divide(a, b):
    """Returns quotient of two numbers (raises ZeroDivisionError if divisor is zero)."""
    return a / b

def power(a, b):
    """Returns a raised to the power of b"""
    return a ** b

def square(a):
    """Returns the square of a number."""
    return a ** 2

def cube(a):
    """Returns the cube of a number."""
    return a ** 3

def modulo(a, b):
    return a % b